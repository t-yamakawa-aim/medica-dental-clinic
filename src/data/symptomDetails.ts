// 症状別 詳細ページ用データ
// まずは「痛い・しみる・腫れた・血が出た・歯がぐらぐらする」の1例分を実装。
// 他の症状はこのデータ構造を追加していくことで拡張できます。

export type TreatmentTableRow = {
  label: string
  value: string
}

// 前後比較画像（治療前・治療後を並べて表示）
export type BeforeAfterImage = {
  before: { src: string; alt: string }
  after: { src: string; alt: string }
}

// 治療法の詳細ブロック（見出し＋本文＋画像＋比較テーブルなどを持つ、入れ子可能な単位）
// 「矯正」の中の「ワイヤー矯正」「マウスピース矯正」、
// 「インプラント」の中の「遊離歯肉移植術」「骨誘導再生療法」など、
// 治療法ごとに独立した画像・テーブルを持つケースに対応するための汎用ブロック。
export type TreatmentBlock = {
  heading: string // 治療法名（h5相当）
  headingNote?: string // 「（自由診療）」などの注記
  body?: string // 説明文（複数段落は\n\nで区切る）
  bulletList?: string[] // 箇条書き
  image?: { src: string; alt: string } // 単体画像
  beforeAfter?: BeforeAfterImage // 治療前後比較画像
  table?: TreatmentTableRow[] // 費用等の比較テーブル
  subBlocks?: TreatmentSubBlock[] // さらに入れ子になったサブ治療法（h6相当）
}

// ブロックの中のサブ項目（例：矯正 > ワイヤー矯正 > 全顎矯正／部分矯正）
export type TreatmentSubBlock = {
  heading: string // h6相当の見出し
  headingNote?: string
  body?: string
  bulletList?: string[]
  image?: { src: string; alt: string }
  beforeAfter?: BeforeAfterImage
  table?: TreatmentTableRow[]
}

export type CauseSection = {
  id: string
  jumpLabel: string
  title: string
  titleSub?: string
  lead: string
  leadNote?: string // leadの後に続く補足段落（box内など）
  image?: { src: string; alt: string }
  treatments?: {
    heading?: string
    body: string
  }[]
  table?: TreatmentTableRow[]
  note?: string
  /** 入れ子構造を持つ複数の治療法ブロック（矯正・インプラントなど複雑な症状ページ用） */
  blocks?: TreatmentBlock[]
}

export type SymptomDetail = {
  slug: string
  title: string
  titleBreaks?: string[] // PC/SP改行を考慮したタイトルの行分割（任意）
  metaDescription: string
  intro: string[]
  causes: CauseSection[]
}

